# =============================================================================
# Survey Analytics Platform — Local PostgreSQL configuration helper
# =============================================================================
# Run interactively from the extracted application folder:
#   source("configure_postgresql.R")
#
# The script tests the connection and migrations before writing .Renviron.
# .Renviron is excluded by .rscignore and must never be committed or uploaded.
# =============================================================================

if (!interactive()) stop("Run configure_postgresql.R from an interactive R/RStudio session.", call. = FALSE)
if (!file.exists("sap_environment.R") || !file.exists("db_backend.R")) {
  stop("Run this script from the Survey Analytics application directory.", call. = FALSE)
}
if (!exists("%||%", mode = "function")) {
  `%||%` <- function(x, y) if (is.null(x) || length(x) == 0L) y else x
}

ask <- function(label, default = "") {
  suffix <- if (nzchar(default)) paste0(" [", default, "]") else ""
  value <- trimws(readline(paste0(label, suffix, ": ")))
  if (nzchar(value)) value else default
}

ask_password <- function() {
  if (requireNamespace("rstudioapi", quietly = TRUE) && isTRUE(rstudioapi::isAvailable())) {
    return(rstudioapi::askForPassword("PostgreSQL password (leave blank to use PGPASSFILE/.pgpass)"))
  }
  message("Password input cannot be hidden in this console. Press Enter to use PGPASSFILE/.pgpass instead.")
  readline("PostgreSQL password: ")
}

host <- ask("Host", "localhost")
port <- suppressWarnings(as.integer(ask("Port", "5432")))
if (is.na(port) || port < 1L || port > 65535L) stop("Invalid PostgreSQL port.", call. = FALSE)
database <- ask("Database", "nexus_studio")
user <- ask("Database user", "sap_app")
password <- ask_password()
schema <- ask("Application schema", "sap")
if (!grepl("^[A-Za-z_][A-Za-z0-9_]*$", schema)) stop("Invalid schema name.", call. = FALSE)
ssl_default <- if (tolower(host) %in% c("localhost", "127.0.0.1", "::1")) "prefer" else "require"
sslmode <- ask("SSL mode", ssl_default)
auto_default <- if (tolower(host) %in% c("localhost", "127.0.0.1", "::1")) "yes" else "no"
auto_create <- tolower(ask("Create the database if it does not exist? (yes/no)", auto_default)) %in% c("y", "yes", "true", "1")

Sys.setenv(
  SAP_RUNTIME_PROFILE = "development",
  SAP_DEMO_MODE = "false",
  SAP_DB_REQUIRED = "false",
  SAP_AUTH_REQUIRED = "true",
  SAP_ALLOW_GUEST = "true",
  SAP_STARTUP_ALLOW_DEMO_FALLBACK = "true",
  SAP_PG_HOST = host,
  SAP_PG_PORT = as.character(port),
  SAP_PG_DB = database,
  SAP_PG_USER = user,
  SAP_PG_PASSWORD = password,
  SAP_PG_SCHEMA = schema,
  SAP_PG_SSLMODE = sslmode,
  SAP_PG_AUTO_CREATE_DB = if (auto_create) "true" else "false"
)

source("sap_environment.R", local = FALSE)
source("db_backend.R", local = FALSE)

message("Testing PostgreSQL and applying idempotent migrations...")
con <- NULL
ok <- tryCatch({
  con <- db_connect_direct()
  health <- db_init(con)
  message("Connected to database '", health$database_name[[1]], "', schema '", health$active_schema[[1]], "'.")
  TRUE
}, error = function(e) {
  message("PostgreSQL test failed: ", conditionMessage(e))
  FALSE
}, finally = {
  if (!is.null(con)) db_disconnect(con)
})
if (!isTRUE(ok)) stop("No configuration file was written because the PostgreSQL test failed.", call. = FALSE)

entries <- c(
  SAP_RUNTIME_PROFILE = "development",
  SAP_DEMO_MODE = "false",
  SAP_DB_REQUIRED = "false",
  SAP_AUTH_REQUIRED = "true",
  SAP_ALLOW_GUEST = "true",
  SAP_STARTUP_ALLOW_DEMO_FALLBACK = "true",
  SAP_PG_HOST = host,
  SAP_PG_PORT = as.character(port),
  SAP_PG_DB = database,
  SAP_PG_USER = user,
  SAP_PG_PASSWORD = password,
  SAP_PG_SCHEMA = schema,
  SAP_PG_SSLMODE = sslmode,
  SAP_PG_AUTO_CREATE_DB = if (auto_create) "true" else "false"
)

escape_env <- function(x) {
  x <- gsub("\\\\", "\\\\\\\\", as.character(x))
  x <- gsub('"', '\\\\"', x, fixed = TRUE)
  paste0('"', x, '"')
}

path <- file.path(getwd(), ".Renviron")
existing <- if (file.exists(path)) readLines(path, warn = FALSE, encoding = "UTF-8") else character()
keys <- names(entries)
keep <- existing[!vapply(existing, function(line) {
  any(vapply(keys, function(k) grepl(paste0("^[[:space:]]*", k, "[[:space:]]*="), line), logical(1)))
}, logical(1))]
new_lines <- c(
  keep,
  if (length(keep) && nzchar(tail(keep, 1))) "" else character(),
  "# Survey Analytics PostgreSQL settings — generated by configure_postgresql.R",
  vapply(seq_along(entries), function(i) paste0(keys[[i]], "=", escape_env(entries[[i]])), character(1))
)
writeLines(new_lines, path, useBytes = TRUE)
try(Sys.chmod(path, mode = "0600"), silent = TRUE)
message("Saved ", normalizePath(path, winslash = "/", mustWork = FALSE), ". Restart R, then run shiny::runApp().")
